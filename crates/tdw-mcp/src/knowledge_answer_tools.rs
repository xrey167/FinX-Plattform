#![allow(clippy::doc_markdown)] // narrative docstrings describe MCP surface
//! `tdw.kg.answer` — GraphRAG-style cited answer synthesis (knowledge-system K-M3).
//!
//! # Retrieve → Expand → Answer pipeline
//!
//! [`execute`] drives three sequenced phases:
//!
//! 1. **RETRIEVE** — hybrid search via the platform [`Retriever`], honouring the
//!    `as_of` temporal gate (leakage-safe: all hits carry `as_of` that is ≤ the
//!    query cutoff, enforced by the retriever's payload predicates and the graph
//!    channel's [`document_visible`] gate — not re-implemented here).
//! 2. **EXPAND** — optional k-hop graph expansion (`k_hop` arg → [`GraphExpansion`]),
//!    also leakage-safe because the retriever applies the same temporal filter to
//!    expansion paths.
//! 3. **ANSWER** — assemble a cited answer from the retrieved hit set:
//!    - **Synthesized stub** (only reachable via the `TDW_ALLOW_STUB_FEEDBACK=1`
//!      operator override — no production `LanguageModel` is wired into the runtime
//!      yet, #345): exercises the synthesis code-path with inline `[doc-id]`
//!      citations but is stamped truthfully as a stub, never bare `"synthesized"`.
//!    - **Extractive** (default — no model / stub model): top passages + citation
//!      list, clearly labelled `"extractive (no model configured)"`. Keyless
//!      installs get a fully functional extractive path.
//!
//! # Citation-validity contract
//!
//! Every cited document id MUST appear in the retrieved hit set returned by the
//! retriever — hallucinated citations are structurally impossible because the
//! citation list is built directly from hit ids, not generated by an LLM.
//!
//! In synthesized mode the LLM sees explicit inline markers (`[doc-id]` in the
//! prompt) and is instructed to cite only those ids; the post-processing step
//! validates that every id appearing in the NL answer is in the retrieved set
//! before returning the response. Any out-of-set id is stripped with a loud
//! `"citation_validity_warning"` so callers always know the answer was filtered.
//!
//! # Point-in-time (finance differentiator)
//!
//! The `as_of` argument makes answers backtest-safe.  A query with
//! `as_of = "2024-01-01"` must never surface, cite, or synthesize from a fact
//! dated after that date.  This guarantee is delegated entirely to the
//! [`Retriever`]: the payload `as_of ≤ cutoff` condition excludes undated and
//! future-dated documents from every channel (vector, lexical, tag, graph).
//! The answer tool trusts and re-exposes this guarantee without re-implementing
//! temporal filtering, so leakage bugs cannot originate here independently.
//!
//! # Confidence
//!
//! K-R6 confidence scores carried on [`RetrievedHit`]s are surfaced on each
//! citation and as an aggregate `answer_confidence` (mean of cited hit scores, or
//! `null` when no hits carry confidence).  See [`AnswerCitation`].
//!
//! # Mode stamp
//!
//! The response always carries a truthful `"mode"` stamp: either
//! `"extractive (no model configured)"` or
//! `"synthesized (stub model — not production NL synthesis)"` — never a bare
//! `"synthesized"` while a real production `LanguageModel` is unwired — so
//! callers can never mistake stub boilerplate for production NL synthesis.

