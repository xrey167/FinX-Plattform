/// The tool name owned by this module.
pub const TOOL_NAME: &str = "tdw.kg.answer";

/// Whether `name` is the answer tool.
#[must_use]
pub fn owns(name: &str) -> bool {
    name == TOOL_NAME
}

// ── Caps ──────────────────────────────────────────────────────────────────────

/// Maximum characters in a query string (mirrors `tdw.kg.search`).
const MAX_QUERY_CHARS: usize = 8192;

/// Default number of retrieved hits assembled into the answer context.
const DEFAULT_TOP_K: usize = 8;

/// Maximum answer hits (capped to avoid unbounded context assembly).
const MAX_ANSWER_TOP_K: usize = 32;

/// Maximum characters for the NL synthesis prompt passage per hit.
const MAX_PASSAGE_CHARS: usize = 2_048;

/// Maximum total characters contributed to the synthesis prompt across all hits.
const MAX_PROMPT_CONTEXT_CHARS: usize = 24_576;

/// Maximum output tokens requested from the language model (reserved for #345 production wiring).
#[allow(dead_code)]
const MAX_OUTPUT_TOKENS: u32 = 1_024;

// ── Mode stamps (truthful) ──────────────────────────────────────────────────

/// Extractive mode stamp: no language model — top passages + citation list.
const MODE_EXTRACTIVE: &str = "extractive (no model configured)";

/// Stub-synthesis mode stamp. The synthesized code-path is exercised but the
/// answer text is assembled deterministically (no production LLM is wired into
/// `KnowledgeRuntime` yet — #345). The stamp MUST NOT claim bare `"synthesized"`
/// because that would misrepresent a stub as production NL synthesis (K-M3
/// citation-honesty guarantee). Until a real `LanguageModel` is wired, the only
/// way to reach this path is the `TDW_ALLOW_STUB_FEEDBACK=1` operator override.
const MODE_SYNTHESIZED_STUB: &str = "synthesized (stub model — not production NL synthesis)";

